// ---------------------------------------------------------------------------
// EXIM-08: export --output writes to file
//
// The binary does not support env-var path overrides, so we test the
// --output flag acceptance via CLI (nonexistent session reaches session
// lookup, proving the flag is parsed) and verify file-writing logic at
// the library level.
// ---------------------------------------------------------------------------

#[test]
fn test_export_output_flag_accepted_by_cli() {
    // Verify --output flag is parsed: error should be "not found" (session
    // lookup), not a flag parse error.
    #[allow(deprecated)]
    let mut cmd = assert_cmd::Command::cargo_bin("rec").expect("binary 'rec' should be findable");

    cmd.args([
        "export",
        "nonexistent-output-test-xyz",
        "--format",
        "bash",
        "--output",
        "/tmp/rec-test-export-output.sh",
    ]);
    cmd.assert().failure().code(1);
}

#[test]
fn test_export_output_writes_file_library() {
    let env = TestEnv::new();
    let session = env.create_session_with_commands("file-export", &["echo hello"]);

    let content = rec::export::export_bash(&session, None);
    let output_path = env.paths.data_dir.join("exported.sh");
    std::fs::write(&output_path, &content).expect("write should succeed");

    let read_back = std::fs::read_to_string(&output_path).expect("file should exist");
    assert!(
        read_back.starts_with("#!/bin/bash\n"),
        "file must have shebang"
    );
    assert!(
        read_back.contains("set -euo pipefail"),
        "file must have strict mode"
    );
}

// ---------------------------------------------------------------------------
// EXIM-09: detect_all_parameters detects env values
// ---------------------------------------------------------------------------

#[test]
fn test_parameterize_detects_env_values() {
    let mut env_map = HashMap::new();
    env_map.insert("HOME".to_string(), "/home/alice".to_string());
    env_map.insert("USER".to_string(), "alice".to_string());

    let session = session_with_env(
        "param-detect",
        env_map,
        "workstation",
        &[
            ("ls /home/alice/docs", "/home/alice"),
            ("whoami | grep alice", "/tmp"),
            ("ssh workstation", "/tmp"),
        ],
    );

    let params = detect_all_parameters(&session);

    let names: Vec<&str> = params.iter().map(|p| p.name.as_str()).collect();
    assert!(names.contains(&"HOME_DIR"), "must detect HOME_DIR");
    assert!(names.contains(&"USERNAME"), "must detect USERNAME");
    assert!(names.contains(&"HOSTNAME"), "must detect HOSTNAME");
    assert!(
        params.iter().all(|p| p.auto_detected),
        "all should be auto-detected"
    );
}

// ---------------------------------------------------------------------------
// EXIM-10: parameter value override replaces original values
// ---------------------------------------------------------------------------

#[test]
fn test_param_value_override_replaces_in_output() {
    let mut env_map = HashMap::new();
    env_map.insert("HOME".to_string(), "/home/alice".to_string());

    let session = session_with_env(
        "param-override",
        env_map,
        "unknown",
        &[("cat /home/alice/file.txt", "/home/alice")],
    );

    let params = vec![Parameter {
        name: "HOME_DIR".to_string(),
        original: "/home/alice".to_string(),
        value: Some("/opt/deploy".to_string()),
        auto_detected: true,
    }];

    let result = rec::export::export_bash(&session, Some(&params));

    // Variable declaration should use override value
    assert!(
        result.contains("HOME_DIR=\"/opt/deploy\""),
        "declaration must use override value"
    );
    // Commands should reference the variable, not original value
    assert!(
        result.contains("$HOME_DIR"),
        "commands must use variable reference"
    );
    assert!(
        !result.contains("/home/alice"),
        "original value must not appear in commands"
    );
}

