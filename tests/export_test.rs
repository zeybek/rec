// ---------------------------------------------------------------------------
// Helper: create a session with specific env vars and hostname
// ---------------------------------------------------------------------------

#[allow(clippy::cast_possible_truncation, clippy::cast_precision_loss)]
fn session_with_env(
    name: &str,
    env: HashMap<String, String>,
    hostname: &str,
    commands: &[(&str, &str)],
) -> Session {
    let cmds: Vec<Command> = commands
        .iter()
        .enumerate()
        .map(|(i, (cmd, cwd))| Command {
            index: i as u32,
            command: cmd.to_string(),
            cwd: PathBuf::from(cwd),
            started_at: 1_700_000_000.0 + i as f64,
            ended_at: Some(1_700_000_001.0 + i as f64),
            exit_code: Some(0),
            duration_ms: Some(1000),
        })
        .collect();

    let count = cmds.len() as u32;
    Session {
        header: SessionHeader {
            version: 2,
            id: Uuid::new_v4(),
            name: name.to_string(),
            shell: "bash".to_string(),
            os: "linux".to_string(),
            hostname: hostname.to_string(),
            env,
            tags: Vec::new(),
            recovered: None,
            started_at: 1_700_000_000.0,
        },
        commands: cmds,
        footer: Some(SessionFooter {
            ended_at: 1_700_000_060.0,
            command_count: count,
            status: SessionStatus::Completed,
        }),
    }
}

// ---------------------------------------------------------------------------
// EXIM-01: export_bash produces valid bash script
// ---------------------------------------------------------------------------

#[test]
fn test_export_bash_produces_valid_script() {
    let env = TestEnv::new();
    let session = env.create_session_with_commands("bash-export", &["echo hello", "ls -la"]);

    let result = rec::export::export_bash(&session, None);

    assert!(result.starts_with("#!/bin/bash\n"), "must have shebang");
    assert!(
        result.contains("set -euo pipefail"),
        "must have strict mode"
    );
    assert!(result.contains("echo hello"), "must contain commands");
    assert!(result.contains("ls -la"), "must contain all commands");
    assert!(
        result.contains("# Generated by rec"),
        "must have generator comment"
    );
}

